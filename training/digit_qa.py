"""Stage 2 toy experiment — a nontrivial spoken input -> spoken response mapping, audio only.

Task ("digit successor"): a user says a digit d (Free Spoken Digit Dataset, CC BY-SA 4.0); RAVEL must answer
(d + 1) mod 10 *in speech*, in a fixed AI voice (FSDD speaker 'jackson'), after the user finishes.
No text anywhere: inputs are microphone log-mels, outputs are EnCodec tokens generated by the DNAG and decoded
by the frozen codec. When to start/stop speaking is decided by the learned policy head (behaviour cloning).

Evaluation: generated answer audio is classified by an independent CNN digit classifier trained ONLY on real
recordings (with codec round-trip augmentation). Held-out user takes (40-49) are used for testing.
Chance accuracy = 10%. "Repeat" rate = how often the answer is classified as the *user's* digit.

    python training/digit_qa.py prepare --fsdd /path/fsdd/recordings --out data/fsdd24k.pt
    python training/digit_qa.py classifier --data data/fsdd24k.pt --out checkpoints/digit_clf.pt
    python training/digit_qa.py train --data data/fsdd24k.pt --out checkpoints/digit_qa --steps 2000
    python training/digit_qa.py eval --data data/fsdd24k.pt --ckpt checkpoints/digit_qa/final.pt \
        --clf checkpoints/digit_clf.pt --out results/digit_qa.json
"""
import argparse
import glob
import json
import os
import sys

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from scipy.signal import resample_poly

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ravel.config import load_config, micro_overrides  # noqa: E402
from ravel.features import CausalLogMel  # noqa: E402

SLOT = 960
AI_SPK = "jackson"
USERS = ["george", "lucas", "nicolas", "theo", "yweweler"]
QA_ACTIONS = ["silent", "speak"]
S_EP = 48  # 1.92 s episodes


def trim(x, rel_db=35.0, margin=480):
    hop = 240
    n = len(x) // hop
    e = 10 * np.log10((x[: n * hop].reshape(n, hop) ** 2).mean(1) + 1e-10)
    a = np.where(e > e.max() - rel_db)[0]
    return x[max(0, a[0] * hop - margin):min(len(x), (a[-1] + 1) * hop + margin)] if len(a) else x


# ------------------------------------------------------------------ data preparation
def prepare(fsdd_dir, out):
    import soundfile as sf
    from ravel.codec import FrozenCodec
    codec = FrozenCodec()
    clips = {}
    for p in sorted(glob.glob(os.path.join(fsdd_dir, "*.wav"))):
        d, spk, take = os.path.basename(p)[:-4].split("_")
        x, sr = sf.read(p, dtype="float32")
        assert sr == 8000
        y = trim(resample_poly(x, 3, 1).astype(np.float32))
        y = 0.5 * y / (np.abs(y).max() + 1e-6)
        y = np.pad(y, (0, (-len(y)) % SLOT))
        rec = {"wav": y, "digit": int(d), "spk": spk, "take": int(take)}
        if spk == AI_SPK:
            rec["tokens"] = codec.encode(torch.from_numpy(y)[None])[0].to(torch.int16)
        clips.setdefault(spk, []).append(rec)
    torch.save({"clips": clips, "silence": codec.silence_slot(3).to(torch.int16)}, out)
    print({k: len(v) for k, v in clips.items()})


class DigitEpisodes:
    def __init__(self, data_path, split="train", seed=0):
        d = torch.load(data_path, weights_only=False)
        self.silence = d["silence"].long()
        takes = range(0, 40) if split == "train" else range(40, 50)
        # drop rare outlier recordings longer than 0.8 s (20 slots) so every episode fits in S_EP slots
        self.users = [c for s in USERS for c in d["clips"][s] if c["take"] in takes and len(c["wav"]) <= 20 * SLOT]
        ai = [c for c in d["clips"][AI_SPK] if c["take"] < 40]  # AI answers always from training takes
        self.ai_by_digit = {k: [c for c in ai if c["digit"] == k] for k in range(10)}
        self.rng = np.random.default_rng(seed)
        self.mel = CausalLogMel()

    def episode(self, rng, user_clip=None):
        u = user_clip or self.users[rng.integers(len(self.users))]
        target = (u["digit"] + 1) % 10
        a = self.ai_by_digit[target][rng.integers(len(self.ai_by_digit[target]))]
        lead = int(rng.integers(2, 6))
        u_slots = len(u["wav"]) // SLOT
        gap = int(rng.integers(4, 7))
        a_start = lead + u_slots + gap
        a_slots = len(a["wav"]) // SLOT
        if a_start + a_slots > S_EP:
            a_slots = S_EP - a_start
        user = np.zeros(S_EP * SLOT, np.float32)
        n = min(len(u["wav"]), (S_EP - lead) * SLOT)
        user[lead * SLOT: lead * SLOT + n] = u["wav"][:n]
        ai = np.zeros(S_EP * SLOT, np.float32)
        ai[a_start * SLOT:(a_start + a_slots) * SLOT] = a["wav"][: a_slots * SLOT]
        tok = self.silence[None].repeat(S_EP, 1, 1).clone()
        tok[a_start:a_start + a_slots] = a["tokens"][: 3 * a_slots].long().view(a_slots, 3, -1)
        actions = np.zeros(S_EP, np.int64)
        actions[a_start:a_start + a_slots] = 1
        g = 10 ** (rng.uniform(-20, -8) / 20)
        echo = np.concatenate([np.zeros(96, np.float32), ai[:-96]]) * g
        mic = user + echo + 10 ** (rng.uniform(-60, -48) / 20) * rng.standard_normal(len(user)).astype(np.float32)
        e = 10 * np.log10((user.reshape(2 * S_EP, -1).astype(np.float64) ** 2).mean(1) + 1e-12)
        return {"mic": mic, "ref": ai, "user": user, "echo_gain": g, "tokens": tok, "actions": actions,
                "user_vad_tick": (e > -42).astype(np.float32),
                "user_digit": u["digit"], "target": target, "a_start": a_start, "user_end": lead + u_slots}

    def batch(self, B, rng):
        eps = [self.episode(rng) for _ in range(B)]
        mic = torch.from_numpy(np.stack([e["mic"] for e in eps]))
        ref = torch.from_numpy(np.stack([e["ref"] for e in eps]))
        with torch.no_grad():
            mm, rm = self.mel(mic), self.mel(ref)
        S = S_EP
        uv = torch.from_numpy(np.stack([e["user_vad_tick"] for e in eps])).view(B, S, 2).amax(-1)
        act = torch.from_numpy(np.stack([e["actions"] for e in eps]))
        return {"mic_mel": mm, "ref_mel": rm, "ai_tokens": torch.stack([e["tokens"] for e in eps]), "actions": act,
                "user_vad_tick": torch.from_numpy(np.stack([e["user_vad_tick"] for e in eps])),
                "user_vad": uv, "ai_active": act.float(),
                "relevance": torch.from_numpy(np.stack([(np.arange(S) >= e["user_end"]) & (e["actions"].cumsum() < e["actions"].sum())
                                                        for e in eps])).float()}


# ------------------------------------------------------------------ independent digit classifier
class DigitCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.mel = CausalLogMel()
        self.net = nn.Sequential(nn.Conv2d(1, 32, 3, padding=1), nn.BatchNorm2d(32), nn.ReLU(), nn.MaxPool2d(2),
                                 nn.Conv2d(32, 64, 3, padding=1), nn.BatchNorm2d(64), nn.ReLU(), nn.MaxPool2d(2),
                                 nn.Conv2d(64, 128, 3, padding=1), nn.BatchNorm2d(128), nn.ReLU(),
                                 nn.AdaptiveMaxPool2d((4, 1)), nn.Flatten(), nn.Dropout(0.3), nn.Linear(512, 10))

    def forward(self, wav):
        m = self.mel(wav)  # (B, T, 80)
        m = (m - m.mean((1, 2), keepdim=True)) / (m.std((1, 2), keepdim=True) + 1e-5)
        return self.net(m.transpose(1, 2)[:, None])


def _fix_len(x, n=24000):
    x = x[:n]
    return np.pad(x, (0, n - len(x)))


def train_classifier(data_path, out, steps=1500, seed=0):
    from ravel.codec import FrozenCodec
    torch.manual_seed(seed)
    rng = np.random.default_rng(seed)
    d = torch.load(data_path, weights_only=False)
    codec = FrozenCodec()
    tr = [c for s in d["clips"].values() for c in s if c["take"] < 45]
    te = [c for s in d["clips"].values() for c in s if c["take"] >= 45]
    # codec round-trip copies so the classifier works on decoded audio
    def rt(clips):
        out_ = []
        for i in range(0, len(clips), 64):
            w = torch.from_numpy(np.stack([_fix_len(c["wav"]) for c in clips[i:i + 64]]))
            out_.append(codec.decode(codec.encode(w)).numpy())
        return np.concatenate(out_)
    tr_wav = np.stack([_fix_len(c["wav"]) for c in tr])
    tr_rt = rt(tr)
    te_wav = np.stack([_fix_len(c["wav"]) for c in te])
    te_rt = rt(te)
    ytr = torch.tensor([c["digit"] for c in tr])
    yte = torch.tensor([c["digit"] for c in te])
    clf = DigitCNN()
    opt = torch.optim.AdamW(clf.parameters(), 1e-3, weight_decay=1e-3)
    for step in range(steps):
        idx = rng.integers(len(tr), size=64)
        src = np.where(rng.random(64)[:, None] < 0.5, tr_wav[idx], tr_rt[idx])
        shift = rng.integers(0, 4800, size=64)
        src = np.stack([np.roll(x, s) * rng.uniform(0.3, 1.5) for x, s in zip(src, shift)])
        src = src + 10 ** (rng.uniform(-70, -45) / 20) * rng.standard_normal(src.shape)
        loss = F.cross_entropy(clf(torch.from_numpy(src.astype(np.float32))), ytr[idx])
        opt.zero_grad()
        loss.backward()
        opt.step()
    clf.eval()
    with torch.no_grad():
        acc = float((clf(torch.from_numpy(te_wav)).argmax(-1) == yte).float().mean())
        acc_rt = float((clf(torch.from_numpy(te_rt.astype(np.float32))).argmax(-1) == yte).float().mean())
        ai_te = [i for i, c in enumerate(te) if c["spk"] == AI_SPK]
        acc_ai = float((clf(torch.from_numpy(te_rt[ai_te].astype(np.float32))).argmax(-1) == yte[ai_te]).float().mean())
    rep = {"heldout_real_acc": acc, "heldout_codec_roundtrip_acc": acc_rt, "heldout_ai_voice_roundtrip_acc": acc_ai,
           "n_test": len(te)}
    torch.save({"model": clf.state_dict(), "report": rep}, out)
    print(json.dumps(rep))
    return rep


# ------------------------------------------------------------------ RAVEL training / evaluation
def qa_config():
    ov = dict(micro_overrides())
    ov.update({"actions": QA_ACTIONS, "rif.enabled": False, "core.d_intent": 0})
    return load_config("configs/ravel_tiny.yaml", ov)


QA_WEIGHTS = {"dnag": 1.0, "probe": 0.2, "apc": 0.2, "user_vad": 0.3, "bc": 1.0, "relevance": 0.0,
              "plan_activity": 0.3, "plan_stability": 0.01}


def train(data_path, out, steps, batch, seed, threads):
    from ravel.model import RAVEL
    from training.losses import compute_losses
    from training.trainer import Trainer, set_seed
    torch.set_num_threads(threads)
    set_seed(seed)
    ds = DigitEpisodes(data_path, "train", seed)
    model = RAVEL(qa_config())
    rng = np.random.default_rng(seed)
    tr = Trainer(model, out, lr=1e-3, total_steps=steps, warmup=100, ckpt_every=250, log_every=25)
    tr.maybe_resume()
    tr.fit(lambda s: ds.batch(batch, rng), lambda m, b: compute_losses(m, b, m.forward_train(b), QA_WEIGHTS))
    tr.save("final.pt")


@torch.no_grad()
def evaluate(data_path, ckpt, clf_path, out, n=250, temperature=0.7, seed=0, mode="policy"):
    """Closed-loop, audio-only: the model listens tick by tick, its policy decides when to speak, the DNAG
    generates tokens and the frozen codec decodes them (streaming, 75-frame context). The microphone hears the
    user plus an echo of the model's OWN generated audio. mode='forced' instead forces speaking for 14 slots from
    the reference answer time (isolates content generation from timing)."""
    from inference.streaming import StreamingRAVEL
    from ravel.codec import FrozenCodec
    from ravel.config import from_dict
    from ravel.model import RAVEL
    torch.manual_seed(seed)
    ck = torch.load(ckpt, weights_only=False)
    model = RAVEL(from_dict(ck["config"])).eval()
    model.load_state_dict(ck["model"])
    clf = DigitCNN().eval()
    c = torch.load(clf_path, weights_only=False)
    clf.load_state_dict(c["model"])
    codec = FrozenCodec()
    ds = DigitEpisodes(data_path, "test", seed)
    rng = np.random.default_rng(seed)
    B = 50
    res = {"correct": 0, "repeat": 0, "spoke": 0, "n": 0, "onset_delay_slots": [], "speech_slots": []}
    confusion = np.zeros((10, 10), int)
    examples = []
    for b0 in range(0, n, B):
        eps = [ds.episode(rng, ds.users[((b0 + i) * len(ds.users)) // n]) for i in range(min(B, n - b0))]
        Bn = len(eps)
        sr = StreamingRAVEL(model, codec=codec, decide_mode="prior", temperature=temperature, top_k=50,
                            silence_tokens=ds.silence)
        sr.reset(Bn)
        user = torch.from_numpy(np.stack([e["user"] for e in eps]))
        g = torch.tensor([e["echo_gain"] for e in eps])[:, None]
        ai_track = torch.zeros(Bn, S_EP * SLOT)
        acts = torch.zeros(Bn, S_EP, dtype=torch.long)
        for s in range(S_EP - 1):
            for j in range(2):
                a0 = s * SLOT + j * 480
                played = sr.cur_audio[:, j * 480:(j + 1) * 480]
                mic = user[:, a0:a0 + 480] + g * played + 1e-3 * torch.randn(Bn, 480)
                forced = None
                if mode == "forced" and j == 1:
                    forced = torch.tensor([int(e["a_start"] <= s + 1 < e["a_start"] + 14) for e in eps])
                o = sr.process_tick(mic, forced_action=forced)
            acts[:, s + 1] = o["action"]
            ai_track[:, (s + 1) * SLOT:(s + 2) * SLOT] = o["audio"]
        for i, e in enumerate(eps):
            sp = acts[i].numpy().astype(bool)
            res["n"] += 1
            if not sp.any():
                continue
            res["spoke"] += 1
            first = int(np.argmax(sp))
            res["onset_delay_slots"].append(first - e["user_end"])
            res["speech_slots"].append(int(sp.sum()))
            seg = ai_track[i, first * SLOT:(first + 25) * SLOT].numpy()
            pred = int(clf(torch.from_numpy(_fix_len(seg)[None])).argmax(-1))
            confusion[e["target"], pred] += 1
            res["correct"] += int(pred == e["target"])
            res["repeat"] += int(pred == e["user_digit"])
            if len(examples) < 8:
                examples.append((e, ai_track[i].numpy(), pred))
    rep = {"mode": mode, "n_episodes": res["n"], "spoke_rate": res["spoke"] / res["n"],
           "answer_accuracy": res["correct"] / res["n"],
           "answer_accuracy_given_spoke": res["correct"] / max(1, res["spoke"]),
           "repeat_user_digit_rate": res["repeat"] / res["n"], "chance": 0.1,
           "onset_delay_slots_mean": float(np.mean(res["onset_delay_slots"])) if res["onset_delay_slots"] else None,
           "speech_slots_mean": float(np.mean(res["speech_slots"])) if res["speech_slots"] else None,
           "classifier_report": c["report"], "confusion_target_x_pred": confusion.tolist(), "temperature": temperature}
    print(json.dumps({k: v for k, v in rep.items() if k != "confusion_target_x_pred"}, indent=1))
    if out:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w") as f:
            json.dump(rep, f, indent=2)
        import soundfile as sf
        ex_dir = os.path.splitext(out)[0] + "_examples"
        os.makedirs(ex_dir, exist_ok=True)
        for k, (e, ai, pred) in enumerate(examples):
            stereo = np.stack([e["user"], ai], 1)  # left = user, right = RAVEL
            sf.write(os.path.join(ex_dir, f"ex{k}_user{e['user_digit']}_target{e['target']}_clf{pred}.wav"), stereo, 24000)
    return rep


@torch.no_grad()
def answer_scoring(data_path, ckpt, out, n=200, seed=0):
    """Does the model's prediction depend on the spoken question in the right way, independently of sampling
    quality? For each held-out question, build the 10 episodes that differ ONLY in which digit the AI answers
    (same user audio, same answer timing, a random training take of that digit), and compute the teacher-forced DNAG
    cross-entropy on the answer slots. 10-way accuracy = how often the correct successor digit gets the lowest CE
    (chance 10%). Also reports how often the *repeated* user digit wins."""
    from ravel.config import from_dict
    from ravel.model import RAVEL
    ck = torch.load(ckpt, weights_only=False)
    model = RAVEL(from_dict(ck["config"])).eval()
    model.load_state_dict(ck["model"])
    ds = DigitEpisodes(data_path, "test", seed)
    rng = np.random.default_rng(seed)
    correct = repeat = correct3 = 0
    margins, margins3 = [], []
    for i in range(n):
        u = ds.users[(i * len(ds.users)) // n]
        base_seed = int(rng.integers(1 << 30))
        eps = []
        for cand in range(10):
            r = np.random.default_rng(base_seed)  # identical lead/gap/echo for all candidates
            e = ds.episode(r, u)
            a = ds.ai_by_digit[cand][int(np.random.default_rng(base_seed + cand).integers(len(ds.ai_by_digit[cand])))]
            # rebuild the AI channel with candidate answer `cand` at the same start slot
            a_start, a_slots = e["a_start"], min(len(a["wav"]) // SLOT, S_EP - e["a_start"])
            ai = np.zeros(S_EP * SLOT, np.float32)
            ai[a_start * SLOT:(a_start + a_slots) * SLOT] = a["wav"][: a_slots * SLOT]
            tok = ds.silence[None].repeat(S_EP, 1, 1).clone()
            tok[a_start:a_start + a_slots] = a["tokens"][: 3 * a_slots].long().view(a_slots, 3, -1)
            act = np.zeros(S_EP, np.int64)
            act[a_start:a_start + a_slots] = 1
            mic = e["user"] + np.concatenate([np.zeros(96, np.float32), ai[:-96]]) * e["echo_gain"]
            eps.append((mic, ai, tok, act, a_start, a_slots))
        mic = torch.from_numpy(np.stack([x[0] for x in eps]))
        ref = torch.from_numpy(np.stack([x[1] for x in eps]))
        b = {"mic_mel": ds.mel(mic), "ref_mel": ds.mel(ref), "ai_tokens": torch.stack([x[2] for x in eps]),
             "actions": torch.from_numpy(np.stack([x[3] for x in eps]))}
        res = model.forward_train(b)
        lg, tg = model.dnag_logits(res, b["ai_tokens"])
        ce = F.cross_entropy(lg.reshape(-1, lg.shape[-1]), tg.reshape(-1), reduction="none").view(10, S_EP - 1, -1).mean(-1)
        scores, scores3 = [], []
        for c_, x in enumerate(eps):
            a_start, a_slots = x[4], x[5]
            scores.append(float(ce[c_, a_start - 1:a_start - 1 + a_slots].mean()))  # decision d predicts slot d+1
            # first 3 answer slots: before the model's own (teacher-forced) output reveals which digit it is saying
            scores3.append(float(ce[c_, a_start - 1:a_start + 2].mean()))
        scores, scores3 = np.array(scores), np.array(scores3)
        target = (u["digit"] + 1) % 10
        correct += int(scores.argmin() == target)
        correct3 += int(scores3.argmin() == target)
        repeat += int(scores.argmin() == u["digit"])
        margins.append(float(np.delete(scores, target).mean() - scores[target]))
        margins3.append(float(np.delete(scores3, target).mean() - scores3[target]))
    from scipy.stats import binomtest
    rep = {"n_questions": n, "ten_way_accuracy": correct / n, "ten_way_accuracy_first3slots": correct3 / n,
           "chance": 0.1, "binom_p_all": binomtest(correct, n, 0.1, alternative="greater").pvalue,
           "binom_p_first3": binomtest(correct3, n, 0.1, alternative="greater").pvalue,
           "repeat_wins_rate": repeat / n, "mean_ce_margin_true_vs_others": float(np.mean(margins)),
           "mean_ce_margin_first3": float(np.mean(margins3)), "ckpt": ckpt}
    print(json.dumps(rep, indent=1))
    if out:
        with open(out, "w") as f:
            json.dump(rep, f, indent=2)
    return rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["prepare", "classifier", "train", "eval", "score"])
    ap.add_argument("--fsdd", default="/home/user/ravel_data/fsdd_dl/fsdd/recordings")
    ap.add_argument("--data", default="data/fsdd24k.pt")
    ap.add_argument("--out", default=None)
    ap.add_argument("--ckpt", default=None)
    ap.add_argument("--clf", default="checkpoints/digit_clf.pt")
    ap.add_argument("--steps", type=int, default=2000)
    ap.add_argument("--batch", type=int, default=32)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--threads", type=int, default=2)
    ap.add_argument("--n", type=int, default=250)
    ap.add_argument("--temperature", type=float, default=0.7)
    ap.add_argument("--mode", default="policy", choices=["policy", "forced"])
    a = ap.parse_args()
    torch.set_num_threads(a.threads)
    if a.cmd == "prepare":
        prepare(a.fsdd, a.out or a.data)
    elif a.cmd == "classifier":
        train_classifier(a.data, a.out or a.clf)
    elif a.cmd == "train":
        train(a.data, a.out, a.steps, a.batch, a.seed, a.threads)
    elif a.cmd == "score":
        answer_scoring(a.data, a.ckpt, a.out, a.n, a.seed)
    else:
        evaluate(a.data, a.ckpt, a.clf, a.out, a.n, a.temperature, a.seed, a.mode)


if __name__ == "__main__":
    main()
